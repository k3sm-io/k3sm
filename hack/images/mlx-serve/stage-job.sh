#!/usr/bin/env bash
#
# stage-job — stage the mlx-serve image on the cluster, in a native Job.
#
# The Job runs build.sh --stage-only inside a native pod on one node: it fetches
# the pinned uv and checks it against its published sha256, installs the pinned
# python-build-standalone interpreter (build.sh asserts the artifact URL) and the
# hash-pinned closure (--require-hashes), precompiles, and leaves the tree on a
# local PersistentVolume. The volume lives under the node's storage tree, which
# only the runtime user can read, so the operator does not read it in place:
# fetch reads the stage as the runtime user, in a short-lived native pod that
# mounts the claim read-only, and streams it over kubectl exec into a directory
# the operator owns. There is no root step and the storage tree stays closed.
# The host then packages that copy as the operator's user (build.sh
# --from-stage) and pushes it. Neither pod carries a credential: no Secret, no
# service-account token, no pull secret. The registry credential stays with the
# operator's user on the host.
#
# The node is chosen with a nodeSelector, never nodeName: the claim binds on the
# scheduler's decision (WaitForFirstConsumer), and a nodeName pod skips the
# scheduler and leaves it Pending.
#
# Usage:
#   hack/images/mlx-serve/stage-job.sh render --node <node>   # print the manifests
#   hack/images/mlx-serve/stage-job.sh apply  --node <node>   # run the Job, wait, print the stage path
#   hack/images/mlx-serve/stage-job.sh path                   # print the stage path on the node
#   hack/images/mlx-serve/stage-job.sh fetch [--dest <dir>]   # copy the stage out, as the runtime user
#   hack/images/mlx-serve/stage-job.sh render-reader --node <node>  # print the reader pod fetch runs
#
# Options: --namespace <ns> (default mlx-serve-build). KUBECTL names the kubectl
# to use (default kubectl). apply waits up to K3SM_MLX_STAGE_TIMEOUT seconds
# (default 3600). UV_CONCURRENT_DOWNLOADS and UV_HTTP_TIMEOUT, when set, are
# rendered into the Job's environment for its uv; unset, uv's defaults apply.
# fetch writes <dest> and <dest>.stamp, replacing an earlier copy; <dest>
# defaults to ${K3SM_MLX_WORK:-$HOME/.cache/k3sm/mlx-serve}/stage, the stage
# selftest.sh reads. It reads the node from the bound volume (--node overrides).
#
# Then, as your own user:
#   hack/images/mlx-serve/stage-job.sh fetch
#   K3SM_BIN=<k3sm> hack/images/mlx-serve/build.sh --from-stage ~/.cache/k3sm/mlx-serve/stage
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"

# ---- pins -------------------------------------------------------------------
# uv, pinned by exact version and by the sha256 the release publishes beside the
# asset (uv-aarch64-apple-darwin.tar.gz.sha256). It is the version that
# generated requirements.lock (build.sh's UV_MIN), and it is the uv whose
# manifest maps build.sh's PY_KEY to build.sh's PY_URL; a later uv maps the same
# key to a newer python-build-standalone build, which build.sh refuses.
UV_VERSION="0.13.5"
UV_SHA256="743f85035a1996ecb350659e01cd9faea9709829be09b1b4b03c73eaf3c9cd73"
UV_URL="https://github.com/astral-sh/uv/releases/download/$UV_VERSION/uv-aarch64-apple-darwin.tar.gz"

NAMESPACE="mlx-serve-build"
NAME="mlx-serve-stage"
READER="mlx-serve-stage-reader"
SRC_CONFIGMAP="mlx-serve-stage-src"
STAGE_SIZE="4Gi"
# The files the Job needs: build.sh and what it reads while staging. Its own
# entry script is rendered below.
SRC_FILES="build.sh requirements.lock k3sm_shard.py k3sm_serve.py"

KUBECTL="${KUBECTL:-kubectl}"
TIMEOUT="${K3SM_MLX_STAGE_TIMEOUT:-3600}"

die() { echo "stage-job: $*" >&2; exit 2; }

usage() {
	awk 'NR > 1 && /^#/ { sub(/^# ?/, ""); print; next } NR > 1 { exit }' "$0"
}

# ---- the in-pod entry script ------------------------------------------------
# Runs in the pod's root directory, where each volume mount appears as a
# relative path (./src, ./stage). uv, its cache and the interpreter download live
# under ./work, which goes away with the pod; only the stage persists. Every
# check fails closed: a digest mismatch exits before anything is run.
print_entry() {
	cat <<'EOF'
#!/bin/bash
# Generated by hack/images/mlx-serve/stage-job.sh; runs inside the stage Job.
set -euo pipefail
umask 022
ROOT="$PWD"
SRC="$ROOT/src"
WORKD="$ROOT/work"
mkdir -p "$WORKD/dl" "$WORKD/bin" "$WORKD/home"
export HOME="$WORKD/home"
export UV_NO_CONFIG=1
export UV_CACHE_DIR="$WORKD/uv-cache"

echo "==> requirements.lock against the digest rendered into the Job"
printf '%s  %s\n' "$LOCK_SHA256" "$SRC/requirements.lock" | /usr/bin/shasum -a 256 -c -

echo "==> uv $UV_VERSION"
/usr/bin/curl -fsSL --proto '=https' -o "$WORKD/dl/uv.tar.gz" "$UV_URL"
printf '%s  %s\n' "$UV_SHA256" "$WORKD/dl/uv.tar.gz" | /usr/bin/shasum -a 256 -c -
/usr/bin/tar -xzf "$WORKD/dl/uv.tar.gz" -C "$WORKD/dl"
/usr/bin/install -m 0755 "$WORKD/dl/uv-aarch64-apple-darwin/uv" "$WORKD/bin/uv"
got="$("$WORKD/bin/uv" --version | /usr/bin/awk '{print $2}')"
if [ "$got" != "$UV_VERSION" ]; then
	echo "uv reports $got, pinned $UV_VERSION" >&2
	exit 2
fi

K3SM_MLX_UV="$WORKD/bin/uv" /bin/bash "$SRC/build.sh" --stage-only --restage \
	--work "$WORKD" --stage "$ROOT/stage/stage"
EOF
}

# ---- render -----------------------------------------------------------------
# uv_download_env prints the uv download settings the caller set, as env entries
# for the Job's container, each with a leading newline so that none set renders
# nothing. They change how uv fetches, never what it accepts: --require-hashes
# and the lockfile still decide that.
uv_download_env() {
	local v val
	for v in UV_CONCURRENT_DOWNLOADS UV_HTTP_TIMEOUT; do
		val="${!v:-}"
		[ -n "$val" ] || continue
		case "$val" in
			*[!0-9]*|0*) die "$v must be a positive integer, got '$val'" ;;
		esac
		printf '\n            - name: %s\n              value: "%s"' "$v" "$val"
	done
}

# json_str prints a file (or stdin, for "-") as one JSON string, which is also a
# valid YAML double-quoted scalar, so the ConfigMap carries every byte verbatim
# whatever the file holds.
json_str() {
	python3 -c '
import json, sys
data = sys.stdin.read() if sys.argv[1] == "-" else open(sys.argv[1]).read()
print(json.dumps(data))
' "$1"
}

render() {
	[ -n "$NODE" ] || die "render needs --node <node> (the node whose volume holds the stage)"
	command -v python3 >/dev/null 2>&1 || die "python3 not found (Xcode command line tools)"
	local f lock_sha uv_env
	for f in $SRC_FILES; do
		[ -f "$HERE/$f" ] || die "missing $HERE/$f"
	done
	lock_sha="$(shasum -a 256 "$HERE/requirements.lock" | awk '{print $1}')"
	uv_env="$(uv_download_env)"

	cat <<EOF
# Generated by hack/images/mlx-serve/stage-job.sh — do not edit by hand.
apiVersion: v1
kind: Namespace
metadata:
  name: $NAMESPACE
---
apiVersion: v1
kind: PersistentVolumeClaim
metadata:
  name: $NAME
  namespace: $NAMESPACE
  labels:
    app.kubernetes.io/name: $NAME
spec:
  accessModes: ["ReadWriteOnce"]
  storageClassName: local-path
  resources:
    requests:
      storage: $STAGE_SIZE
---
apiVersion: v1
kind: ConfigMap
metadata:
  name: $SRC_CONFIGMAP
  namespace: $NAMESPACE
  labels:
    app.kubernetes.io/name: $NAME
data:
EOF
	for f in $SRC_FILES; do
		printf '  %s: %s\n' "$f" "$(json_str "$HERE/$f")"
	done
	printf '  %s: %s\n' "stage-entry.sh" "$(print_entry | json_str -)"

	cat <<EOF
---
apiVersion: batch/v1
kind: Job
metadata:
  name: $NAME
  namespace: $NAMESPACE
  labels:
    app.kubernetes.io/name: $NAME
spec:
  backoffLimit: 0
  activeDeadlineSeconds: $TIMEOUT
  template:
    metadata:
      labels:
        app.kubernetes.io/name: $NAME
    spec:
      restartPolicy: Never
      automountServiceAccountToken: false
      enableServiceLinks: false
      nodeSelector:
        kubernetes.io/os: darwin
        kubernetes.io/hostname: $NODE
      tolerations:
        - key: k3sm.io/provider
          operator: Exists
          effect: NoSchedule
      containers:
        - name: stage
          image: native
          command: ["/bin/bash", "./src/stage-entry.sh"]
          env:
            - name: UV_VERSION
              value: "$UV_VERSION"
            - name: UV_URL
              value: "$UV_URL"
            - name: UV_SHA256
              value: "$UV_SHA256"
            - name: LOCK_SHA256
              value: "$lock_sha"$uv_env
          resources:
            requests:
              cpu: "2"
              memory: 2Gi
          volumeMounts:
            - name: src
              mountPath: /src
              readOnly: true
            - name: stage
              mountPath: /stage
      volumes:
        - name: src
          configMap:
            name: $SRC_CONFIGMAP
        - name: stage
          persistentVolumeClaim:
            claimName: $NAME
EOF
}

# render_reader prints the pod fetch reads the stage through: a native pod on
# the stage's node that mounts the claim read-only and only waits, so the host
# can kubectl exec one tar in it. It runs as the runtime user, the one user that
# can read the storage tree, and carries no credential and no network use.
render_reader() {
	[ -n "$NODE" ] || die "render-reader needs --node <node> (the node whose volume holds the stage)"
	cat <<EOF
# Generated by hack/images/mlx-serve/stage-job.sh — do not edit by hand.
apiVersion: v1
kind: Pod
metadata:
  name: $READER
  namespace: $NAMESPACE
  labels:
    app.kubernetes.io/name: $READER
spec:
  restartPolicy: Never
  activeDeadlineSeconds: 900
  automountServiceAccountToken: false
  enableServiceLinks: false
  nodeSelector:
    kubernetes.io/os: darwin
    kubernetes.io/hostname: $NODE
  tolerations:
    - key: k3sm.io/provider
      operator: Exists
      effect: NoSchedule
  containers:
    - name: reader
      image: native
      command: ["/bin/sleep", "900"]
      volumeMounts:
        - name: stage
          mountPath: /stage
          readOnly: true
  volumes:
    - name: stage
      persistentVolumeClaim:
        claimName: $NAME
        readOnly: true
EOF
}

# ---- cluster verbs ----------------------------------------------------------
# stage_path prints the stage directory on the node, from the bound volume.
stage_path() {
	local pv path
	pv="$("$KUBECTL" -n "$NAMESPACE" get pvc "$NAME" -o jsonpath='{.spec.volumeName}')"
	[ -n "$pv" ] || die "claim $NAMESPACE/$NAME is not bound (has the stage Job been scheduled?)"
	path="$("$KUBECTL" get pv "$pv" -o jsonpath='{.spec.local.path}')"
	[ -n "$path" ] || die "volume $pv has no local path"
	echo "$path/stage"
}

apply() {
	local manifest status deadline
	manifest="$(mktemp "${TMPDIR:-/tmp}/mlx-serve-stage.XXXXXX")"
	# shellcheck disable=SC2064 # expand now: the path is fixed
	trap "rm -f '$manifest'" EXIT
	render > "$manifest"

	# A Job's pod template is immutable, so a re-run replaces the Job. The claim
	# is kept: the stage is rebuilt into it (--restage).
	"$KUBECTL" -n "$NAMESPACE" delete job "$NAME" --ignore-not-found --wait=true >/dev/null 2>&1 || true
	# Server-side: the ConfigMap carries build.sh and the lockfile, which would
	# overflow the annotation a client-side apply records.
	"$KUBECTL" apply --server-side --force-conflicts -f "$manifest"

	echo "==> waiting for job/$NAME (up to ${TIMEOUT}s)"
	deadline=$(( $(date +%s) + TIMEOUT ))
	while :; do
		status="$("$KUBECTL" -n "$NAMESPACE" get job "$NAME" -o jsonpath='{.status.succeeded}/{.status.failed}' 2>/dev/null || true)"
		case "$status" in
			1/*) break ;;
			*/[1-9]*)
				"$KUBECTL" -n "$NAMESPACE" logs "job/$NAME" --tail=60 >&2 || true
				die "job/$NAME failed (logs above)" ;;
		esac
		[ "$(date +%s)" -lt "$deadline" ] || die "job/$NAME did not finish in ${TIMEOUT}s"
		sleep 10
	done
	"$KUBECTL" -n "$NAMESPACE" logs "job/$NAME" --tail=20 || true

	local path
	path="$(stage_path)"
	cat <<EOF

==> staged on the cluster
  stage: $path
  node:  $NODE

The volume is readable only by the runtime user. Copy it out, then package
the copy as your own user (no uv, no network):

  $HERE/stage-job.sh fetch
  K3SM_BIN=<k3sm> $HERE/build.sh --from-stage \${K3SM_MLX_WORK:-\$HOME/.cache/k3sm/mlx-serve}/stage
EOF
}

# stage_node prints the node the bound stage volume is pinned to.
stage_node() {
	local pv node
	pv="$("$KUBECTL" -n "$NAMESPACE" get pvc "$NAME" -o jsonpath='{.spec.volumeName}')"
	[ -n "$pv" ] || die "claim $NAMESPACE/$NAME is not bound (has the stage Job been scheduled?)"
	node="$("$KUBECTL" get pv "$pv" -o jsonpath='{.spec.nodeAffinity.required.nodeSelectorTerms[0].matchExpressions[0].values[0]}')"
	[ -n "$node" ] || die "volume $pv names no node; pass --node"
	echo "$node"
}

# fetch copies the stage and its stamp out of the cluster into DEST, as the
# runtime user: the reader pod mounts the claim read-only and the host runs one
# tar in it over kubectl exec. The copy lands in a temporary directory beside
# DEST and replaces DEST only once the stream is complete, so a failed fetch
# leaves an earlier copy as it was. DEST is replaced only when it is an earlier
# fetch (its stamp sits beside it), never an unrelated directory. bsdtar on the
# host, run as the operator, refuses absolute and .. member names and extracting
# through a symlink, and restores no owner; a stage that arrives as a symlink is
# refused. The stream cannot write outside the temporary directory.
fetch() {
	local dest parent active
	dest="${DEST:-${K3SM_MLX_WORK:-$HOME/.cache/k3sm/mlx-serve}/stage}"
	case "$dest" in /*) ;; *) dest="$PWD/$dest" ;; esac
	case "$dest" in
		*/|*/.|*/..|*/./*|*/../*|*"'"*) die "--dest must be a plain path, got '$dest'" ;;
	esac
	[ "$(printf '%s' "$dest" | tr -cd / | wc -c)" -ge 3 ] && [ "$dest" != "$HOME" ] ||
		die "--dest '$dest' is too close to the root or your home"
	if [ -e "$dest" ] && [ ! -f "$dest.stamp" ]; then
		die "$dest exists and is not an earlier fetch (no $dest.stamp beside it); choose another --dest"
	fi
	[ -n "$NODE" ] || NODE="$(stage_node)"
	stage_path >/dev/null
	active="$("$KUBECTL" -n "$NAMESPACE" get job "$NAME" -o jsonpath='{.status.active}' 2>/dev/null || true)"
	[ -z "$active" ] || [ "$active" = 0 ] || die "job/$NAME is still running; fetch once it has succeeded"
	parent="$(dirname "$dest")"
	mkdir -p "$parent"
	FETCH_TMP="$(mktemp -d "$parent/.stage-fetch.XXXXXX")"
	trap fetch_cleanup EXIT
	render_reader > "$FETCH_TMP.yaml"

	"$KUBECTL" -n "$NAMESPACE" delete pod "$READER" --ignore-not-found --wait=true >/dev/null 2>&1 || true
	"$KUBECTL" apply -f "$FETCH_TMP.yaml" >/dev/null
	"$KUBECTL" -n "$NAMESPACE" wait --for=condition=Ready "pod/$READER" --timeout=180s >/dev/null ||
		die "pod/$READER did not become Ready on $NODE"

	# A native container starts in the pod's root, where the claim's mount
	# appears as the relative path ./stage; /usr/bin/tar is a platform binary
	# the path-rebase shim cannot reach, so the absolute /stage would be the
	# host's. Checked first, so a different start directory fails by name.
	"$KUBECTL" -n "$NAMESPACE" exec "$READER" -- /bin/test -f ./stage/stage.stamp ||
		die "pod/$READER does not see the stage at ./stage/stage.stamp (the container must start in the pod's root)"
	echo "==> reading the stage on $NODE as the runtime user, into $dest"
	"$KUBECTL" -n "$NAMESPACE" exec "$READER" -- /usr/bin/tar -C ./stage -cf - stage stage.stamp |
		/usr/bin/tar -xo -f - -C "$FETCH_TMP" ||
		die "copying the stage out of pod/$READER failed"
	[ -d "$FETCH_TMP/stage" ] && [ ! -L "$FETCH_TMP/stage" ] &&
		[ -f "$FETCH_TMP/stage.stamp" ] && [ ! -L "$FETCH_TMP/stage.stamp" ] ||
		die "the stream from pod/$READER held no stage directory and stamp file"

	rm -rf "$dest.old"
	if [ -e "$dest" ]; then mv "$dest" "$dest.old"; fi
	mv "$FETCH_TMP/stage" "$dest"
	mv "$FETCH_TMP/stage.stamp" "$dest.stamp"
	rm -rf "$dest.old"
	cat <<EOF

==> fetched
  stage: $dest
  stamp: $dest.stamp

Package it as your own user (no uv, no network):

  K3SM_BIN=<k3sm> $HERE/build.sh --from-stage $dest
EOF
}

# fetch_cleanup removes fetch's temporary directory and manifest and deletes the
# reader pod, on every exit.
FETCH_TMP=""
fetch_cleanup() {
	if [ -n "$FETCH_TMP" ]; then rm -rf "$FETCH_TMP" "$FETCH_TMP.yaml"; fi
	"$KUBECTL" -n "$NAMESPACE" delete pod "$READER" --ignore-not-found --wait=false >/dev/null 2>&1 || true
}

# ---- main -------------------------------------------------------------------
VERB="${1:-}"
[ $# -gt 0 ] && shift
NODE=""
DEST=""
while [ $# -gt 0 ]; do
	case "$1" in
		--node) NODE="${2:-}"; [ -n "$NODE" ] || die "--node needs a value"; shift 2 ;;
		--namespace) NAMESPACE="${2:-}"; [ -n "$NAMESPACE" ] || die "--namespace needs a value"; shift 2 ;;
		--dest) DEST="${2:-}"; [ -n "$DEST" ] || die "--dest needs a value"; shift 2 ;;
		-h|--help) usage; exit 0 ;;
		*) die "unknown flag: $1 (try --help)" ;;
	esac
done

case "$VERB" in
	render) render ;;
	apply) apply ;;
	path) stage_path ;;
	fetch) fetch ;;
	render-reader) render_reader ;;
	-h|--help|help) usage ;;
	*) usage >&2; exit 2 ;;
esac
