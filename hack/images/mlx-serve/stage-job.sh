#!/usr/bin/env bash
#
# stage-job — stage the mlx-serve image on the cluster, in a native Job.
#
# The Job runs build.sh --stage-only inside a native pod on one node: it fetches
# the pinned uv and checks it against its published sha256, installs the pinned
# python-build-standalone interpreter (build.sh asserts the artifact URL) and the
# hash-pinned closure (--require-hashes), precompiles, and leaves the tree on a
# local PersistentVolume. The host then packages that volume's stage as the
# operator's user (build.sh --from-stage) and pushes it. The Job carries NO
# credential: no Secret, no service-account token, no pull secret. The registry
# credential stays with the operator's user on the host.
#
# The node is chosen with a nodeSelector, never nodeName: the claim binds on the
# scheduler's decision (WaitForFirstConsumer), and a nodeName pod skips the
# scheduler and leaves it Pending.
#
# Usage:
#   hack/images/mlx-serve/stage-job.sh render --node <node>   # print the manifests
#   hack/images/mlx-serve/stage-job.sh apply  --node <node>   # run the Job, wait, print the stage path
#   hack/images/mlx-serve/stage-job.sh path                   # print the stage path on the node
#
# Options: --namespace <ns> (default mlx-serve-build). KUBECTL names the kubectl
# to use (default kubectl). apply waits up to K3SM_MLX_STAGE_TIMEOUT seconds
# (default 3600).
#
# Then, on that node, as your own user:
#   K3SM_BIN=<k3sm> hack/images/mlx-serve/build.sh --from-stage "$(hack/images/mlx-serve/stage-job.sh path)"
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"

# ---- pins -------------------------------------------------------------------
# uv, pinned by exact version and by the sha256 the release publishes beside the
# asset (uv-aarch64-apple-darwin.tar.gz.sha256). It is the version that
# generated requirements.lock (build.sh's UV_MIN), and it is the uv whose
# manifest maps build.sh's PY_KEY to build.sh's PY_URL; a later uv maps the same
# key to a newer python-build-standalone build, which build.sh refuses.
UV_VERSION="0.12.7"
UV_SHA256="127ebdda7ad953cdf198e964b570ea5771b85467ea93eb7cb6d6f8e6f55408f3"
UV_URL="https://github.com/astral-sh/uv/releases/download/$UV_VERSION/uv-aarch64-apple-darwin.tar.gz"

NAMESPACE="mlx-serve-build"
NAME="mlx-serve-stage"
SRC_CONFIGMAP="mlx-serve-stage-src"
STAGE_SIZE="4Gi"
# The files the Job needs: build.sh and what it reads while staging. Its own
# entry script is rendered below.
SRC_FILES="build.sh requirements.lock k3sm_shard.py k3sm_serve.py"

KUBECTL="${KUBECTL:-kubectl}"
TIMEOUT="${K3SM_MLX_STAGE_TIMEOUT:-3600}"

die() { echo "stage-job: $*" >&2; exit 2; }

usage() {
	awk 'NR > 1 && /^#/ { sub(/^# ?/, ""); print; next } NR > 1 { exit }' "$0"
}

# ---- the in-pod entry script ------------------------------------------------
# Runs in the pod's root directory, where each volume mount appears as a
# relative path (./src, ./stage). uv, its cache and the interpreter download live
# under ./work, which goes away with the pod; only the stage persists. Every
# check fails closed: a digest mismatch exits before anything is run.
print_entry() {
	cat <<'EOF'
#!/bin/bash
# Generated by hack/images/mlx-serve/stage-job.sh; runs inside the stage Job.
set -euo pipefail
umask 022
ROOT="$PWD"
SRC="$ROOT/src"
WORKD="$ROOT/work"
mkdir -p "$WORKD/dl" "$WORKD/bin" "$WORKD/home"
export HOME="$WORKD/home"
export UV_NO_CONFIG=1
export UV_CACHE_DIR="$WORKD/uv-cache"

echo "==> requirements.lock against the digest rendered into the Job"
printf '%s  %s\n' "$LOCK_SHA256" "$SRC/requirements.lock" | /usr/bin/shasum -a 256 -c -

echo "==> uv $UV_VERSION"
/usr/bin/curl -fsSL --proto '=https' -o "$WORKD/dl/uv.tar.gz" "$UV_URL"
printf '%s  %s\n' "$UV_SHA256" "$WORKD/dl/uv.tar.gz" | /usr/bin/shasum -a 256 -c -
/usr/bin/tar -xzf "$WORKD/dl/uv.tar.gz" -C "$WORKD/dl"
/usr/bin/install -m 0755 "$WORKD/dl/uv-aarch64-apple-darwin/uv" "$WORKD/bin/uv"
got="$("$WORKD/bin/uv" --version | /usr/bin/awk '{print $2}')"
if [ "$got" != "$UV_VERSION" ]; then
	echo "uv reports $got, pinned $UV_VERSION" >&2
	exit 2
fi

K3SM_MLX_UV="$WORKD/bin/uv" /bin/bash "$SRC/build.sh" --stage-only --restage \
	--work "$WORKD" --stage "$ROOT/stage/stage"
EOF
}

# ---- render -----------------------------------------------------------------
# json_str prints a file (or stdin, for "-") as one JSON string, which is also a
# valid YAML double-quoted scalar, so the ConfigMap carries every byte verbatim
# whatever the file holds.
json_str() {
	python3 -c '
import json, sys
data = sys.stdin.read() if sys.argv[1] == "-" else open(sys.argv[1]).read()
print(json.dumps(data))
' "$1"
}

render() {
	[ -n "$NODE" ] || die "render needs --node <node> (the node whose volume holds the stage)"
	command -v python3 >/dev/null 2>&1 || die "python3 not found (Xcode command line tools)"
	local f lock_sha
	for f in $SRC_FILES; do
		[ -f "$HERE/$f" ] || die "missing $HERE/$f"
	done
	lock_sha="$(shasum -a 256 "$HERE/requirements.lock" | awk '{print $1}')"

	cat <<EOF
# Generated by hack/images/mlx-serve/stage-job.sh — do not edit by hand.
apiVersion: v1
kind: Namespace
metadata:
  name: $NAMESPACE
---
apiVersion: v1
kind: PersistentVolumeClaim
metadata:
  name: $NAME
  namespace: $NAMESPACE
  labels:
    app.kubernetes.io/name: $NAME
spec:
  accessModes: ["ReadWriteOnce"]
  storageClassName: local-path
  resources:
    requests:
      storage: $STAGE_SIZE
---
apiVersion: v1
kind: ConfigMap
metadata:
  name: $SRC_CONFIGMAP
  namespace: $NAMESPACE
  labels:
    app.kubernetes.io/name: $NAME
data:
EOF
	for f in $SRC_FILES; do
		printf '  %s: %s\n' "$f" "$(json_str "$HERE/$f")"
	done
	printf '  %s: %s\n' "stage-entry.sh" "$(print_entry | json_str -)"

	cat <<EOF
---
apiVersion: batch/v1
kind: Job
metadata:
  name: $NAME
  namespace: $NAMESPACE
  labels:
    app.kubernetes.io/name: $NAME
spec:
  backoffLimit: 0
  activeDeadlineSeconds: $TIMEOUT
  template:
    metadata:
      labels:
        app.kubernetes.io/name: $NAME
    spec:
      restartPolicy: Never
      automountServiceAccountToken: false
      enableServiceLinks: false
      nodeSelector:
        kubernetes.io/os: darwin
        kubernetes.io/hostname: $NODE
      tolerations:
        - key: k3sm.io/provider
          operator: Exists
          effect: NoSchedule
      containers:
        - name: stage
          image: native
          command: ["/bin/bash", "./src/stage-entry.sh"]
          env:
            - name: UV_VERSION
              value: "$UV_VERSION"
            - name: UV_URL
              value: "$UV_URL"
            - name: UV_SHA256
              value: "$UV_SHA256"
            - name: LOCK_SHA256
              value: "$lock_sha"
          resources:
            requests:
              cpu: "2"
              memory: 2Gi
          volumeMounts:
            - name: src
              mountPath: /src
              readOnly: true
            - name: stage
              mountPath: /stage
      volumes:
        - name: src
          configMap:
            name: $SRC_CONFIGMAP
        - name: stage
          persistentVolumeClaim:
            claimName: $NAME
EOF
}

# ---- cluster verbs ----------------------------------------------------------
# stage_path prints the stage directory on the node, from the bound volume.
stage_path() {
	local pv path
	pv="$("$KUBECTL" -n "$NAMESPACE" get pvc "$NAME" -o jsonpath='{.spec.volumeName}')"
	[ -n "$pv" ] || die "claim $NAMESPACE/$NAME is not bound (has the stage Job been scheduled?)"
	path="$("$KUBECTL" get pv "$pv" -o jsonpath='{.spec.local.path}')"
	[ -n "$path" ] || die "volume $pv has no local path"
	echo "$path/stage"
}

apply() {
	local manifest status deadline
	manifest="$(mktemp "${TMPDIR:-/tmp}/mlx-serve-stage.XXXXXX")"
	# shellcheck disable=SC2064 # expand now: the path is fixed
	trap "rm -f '$manifest'" EXIT
	render > "$manifest"

	# A Job's pod template is immutable, so a re-run replaces the Job. The claim
	# is kept: the stage is rebuilt into it (--restage).
	"$KUBECTL" -n "$NAMESPACE" delete job "$NAME" --ignore-not-found --wait=true >/dev/null 2>&1 || true
	# Server-side: the ConfigMap carries build.sh and the lockfile, which would
	# overflow the annotation a client-side apply records.
	"$KUBECTL" apply --server-side --force-conflicts -f "$manifest"

	echo "==> waiting for job/$NAME (up to ${TIMEOUT}s)"
	deadline=$(( $(date +%s) + TIMEOUT ))
	while :; do
		status="$("$KUBECTL" -n "$NAMESPACE" get job "$NAME" -o jsonpath='{.status.succeeded}/{.status.failed}' 2>/dev/null || true)"
		case "$status" in
			1/*) break ;;
			*/[1-9]*)
				"$KUBECTL" -n "$NAMESPACE" logs "job/$NAME" --tail=60 >&2 || true
				die "job/$NAME failed (logs above)" ;;
		esac
		[ "$(date +%s)" -lt "$deadline" ] || die "job/$NAME did not finish in ${TIMEOUT}s"
		sleep 10
	done
	"$KUBECTL" -n "$NAMESPACE" logs "job/$NAME" --tail=20 || true

	local path
	path="$(stage_path)"
	cat <<EOF

==> staged on the cluster
  stage: $path
  node:  $NODE

Package it on that node, as your own user (no uv, no network):

  K3SM_BIN=<k3sm> $HERE/build.sh --from-stage $path
EOF
}

# ---- main -------------------------------------------------------------------
VERB="${1:-}"
[ $# -gt 0 ] && shift
NODE=""
while [ $# -gt 0 ]; do
	case "$1" in
		--node) NODE="${2:-}"; [ -n "$NODE" ] || die "--node needs a value"; shift 2 ;;
		--namespace) NAMESPACE="${2:-}"; [ -n "$NAMESPACE" ] || die "--namespace needs a value"; shift 2 ;;
		-h|--help) usage; exit 0 ;;
		*) die "unknown flag: $1 (try --help)" ;;
	esac
done

case "$VERB" in
	render) render ;;
	apply) apply ;;
	path) stage_path ;;
	-h|--help|help) usage ;;
	*) usage >&2; exit 2 ;;
esac
